#!/usr/bin/env node
/**
 * Regenerates skills/sth-transfer/reference/compatibility.md from the vendored
 * capabilities manifest.
 *
 * The matrix is the STH CLI's contract, not this package's. Retyping 36 cells
 * by hand is how a reference file starts lying: the CLI ships a new dialect,
 * the skill keeps promising the old one, and an agent writes a file the target
 * silently ignores. So the reference is derived, and `tests/reference.test.mjs`
 * fails when the committed file drifts from what this script produces.
 *
 *   node scripts/build-reference.mjs          # write
 *   node scripts/build-reference.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'skills', 'sth-transfer', 'reference', 'compatibility.md')
const SRC = join(root, 'data', 'sth-capabilities-v1.json')

const LEVEL_MEANING = {
  exact: 'converts with no loss',
  lossy: 'converts, something is dropped',
  'native-only': "exists only in that tool's own native format",
  unsupported: 'no conversion path',
}

export function renderReference(manifest) {
  const targets = [...manifest.targets].sort()
  const kinds = [...manifest.artifact_kinds].sort()
  const displayName = new Map(manifest.target_specs.map((spec) => [spec.kind, spec.display_name]))
  const cell = new Map(
    manifest.compatibility.map((entry) => [`${entry.target_kind}/${entry.artifact_kind}`, entry]),
  )

  const lines = [
    '# STH compatibility matrix',
    '',
    '<!-- Generated by scripts/build-reference.mjs. Do not edit by hand. -->',
    '',
    `Schema \`${manifest.schema_version}\`, STH CLI \`${manifest.cli_version}\`.`,
    '',
    'This file is a snapshot for offline reading. `capabilities_get` is',
    'authoritative: it reports the matrix of the CLI actually deployed for the',
    "caller's organization, which may be ahead of this copy.",
    '',
    '## Levels',
    '',
    '| Level | Meaning | What to do |',
    '| --- | --- | --- |',
    `| \`exact\` | ${LEVEL_MEANING.exact} | Convert. State the destination path. |`,
    `| \`lossy\` | ${LEVEL_MEANING.lossy} | Convert **and name what is lost**, before writing anything. |`,
    `| \`native-only\` | ${LEVEL_MEANING['native-only']} | Do not synthesise an equivalent. Explain. |`,
    `| \`unsupported\` | ${LEVEL_MEANING.unsupported} | Say so. Do not improvise a lookalike. |`,
    '',
    '## Matrix',
    '',
    `| Artifact | ${targets.map((target) => displayName.get(target) ?? target).join(' | ')} |`,
    `| --- | ${targets.map(() => '---').join(' | ')} |`,
  ]

  for (const kind of kinds) {
    const row = targets.map((target) => {
      const entry = cell.get(`${target}/${kind}`)
      if (!entry) return '—'
      return entry.implemented ? `\`${entry.level}\`` : `\`${entry.level}\`†`
    })
    lines.push(`| \`${kind}\` | ${row.join(' | ')} |`)
  }

  lines.push(
    '',
    '† the matrix knows the path but the CLI does not yet perform it. Hand the',
    'user the manual steps rather than claiming `sth` will do it.',
    '',
    '## Destinations',
    '',
    '| Target | Artifact | Level | Destination | Invocation |',
    '| --- | --- | --- | --- | --- |',
  )

  for (const target of targets) {
    for (const kind of kinds) {
      const entry = cell.get(`${target}/${kind}`)
      if (!entry || entry.level === 'unsupported') continue
      const destination = entry.destination ? `\`${entry.destination}\`` : '—'
      const invocation = entry.invocation ? `\`${entry.invocation}\`` : '—'
      lines.push(
        `| \`${target}\` | \`${kind}\` | \`${entry.level}\` | ${destination} | ${invocation} |`,
      )
    }
  }

  lines.push('', 'Cells absent from this table are `unsupported`.', '')
  return lines.join('\n')
}

export function loadManifest() {
  return JSON.parse(readFileSync(SRC, 'utf8'))
}

export const REFERENCE_PATH = OUT

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderReference(loadManifest())
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8')
    if (current !== rendered) {
      console.error('compatibility.md is stale. Run: node scripts/build-reference.mjs')
      process.exit(1)
    }
    console.log('compatibility.md is up to date.')
  } else {
    writeFileSync(OUT, rendered)
    console.log(`Wrote ${OUT}`)
  }
}
